    --cases) CASES="${2:-}"; shift 2 ;;
    --with-verify-stack) WITH_STACK=true; shift ;;
    --no-web) NO_WEB=true; shift ;;
    -h | --help) usage ;;
    *) usage ;;
  esac
done

