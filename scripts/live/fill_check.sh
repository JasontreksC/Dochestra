# What an untouched form holds (the combo is preset to its first option by the fixture generator).
DEFAULTS_JSON='{"form_ko.pdf": {"지역": "seoul"}, "form_codes.pdf": {"Dropdown1": "서울"}, "form_multi.pdf": {}}'

SELECTED=()
IFS=',' read -r -a requested <<<"$CASES"
for c in "${requested[@]}"; do
  jq -e --arg c "$c" '.[$c]' <<<"$CASES_JSON" >/dev/null 2>&1 || { echo "fill_check: unknown case '$c' (known: ko, en, codes, multi)" >&2; exit 2; }
