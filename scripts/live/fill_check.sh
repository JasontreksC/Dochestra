# ---- analysis (a one-off uv environment with pypdf + pypdfium2 + pillow) -------------------------
cat >"$FILL_DIR/analyze.py" <<'PYEOF'
import json, sys
from pathlib import Path

import pypdfium2 as pdfium
from PIL import Image, ImageChops
from pypdf import PdfReader

out_dir, label = Path(sys.argv[1]), sys.argv[2]
selected = sys.argv[3].split(",")
cases = json.loads((out_dir / "cases.json").read_text())
defaults = json.loads((out_dir / "defaults.json").read_text())
SCALE = 1.3


def inherited(node, key):
    while node is not None:
        if key in node:
            return node[key]
        node = node["/Parent"].get_object() if "/Parent" in node else None
    return None


def full_name(node):
    parts = []
    while node is not None:
        if "/T" in node:
            parts.append(str(node["/T"]))
        node = node["/Parent"].get_object() if "/Parent" in node else None
    return ".".join(reversed(parts))


def read_widgets(path):
    """One entry per widget annotation: name, kind, stored value, page and rectangle."""
    reader = PdfReader(str(path))
    out = []
    for pno, page in enumerate(reader.pages, 1):
        for ref in page.get("/Annots") or []:
            a = ref.get_object()
            if a.get("/Subtype") != "/Widget":
                continue
            ft = inherited(a, "/FT")
            ff = int(inherited(a, "/Ff") or 0)
            v = inherited(a, "/V")
            name = full_name(a)
            if ft == "/Btn" and ff & (1 << 15):
                kind, value = "radio", (str(v).lstrip("/") if v is not None else None)
            elif ft == "/Btn":
                state = str(v if v is not None else a.get("/AS", "/Off")).lstrip("/")
                kind, value = "checkbox", ("off" if state in ("Off", "") else "on")
            elif ft == "/Ch":
                kind, value = "choice", (str(v) if v is not None else "")
            else:
                kind, value = "text", (str(v) if v is not None else "")
            rect = [float(x) for x in a["/Rect"]]
            out.append(dict(name=name, kind=kind, value=value, page=pno, rect=rect))
    return out


def render(path, png_dir):
    pdf = pdfium.PdfDocument(str(path))
    pdf.init_forms()
    pages = []
    for i in range(len(pdf)):
        image = pdf[i].render(scale=SCALE, may_draw_forms=True).to_pil().convert("RGB")
        if png_dir is not None:
            image.save(png_dir / f"page-{i + 1}.png")
        pages.append((image, pdf[i].get_size()))
    return pages


def changed_fraction(before, after, rect, page_h):
    """Share of pixels inside the widget rectangle that differ between the empty and the filled render."""
    l, b, r, t = rect
    box = tuple(int(v * SCALE) for v in (l, page_h - t, r, page_h - b))
    if box[2] <= box[0] or box[3] <= box[1]:
        return 0.0
    diff = ImageChops.difference(before.crop(box), after.crop(box)).convert("L").point(lambda p: 255 if p > 40 else 0)
    return diff.histogram()[255] / max(1, diff.size[0] * diff.size[1])


results, all_ok = [], True
for case in selected:
    spec = cases[case]
    fixture = spec["fixture"]
    cdir = out_dir / case
    r = dict(case=case, fixture=fixture)
    rr = json.loads((cdir / "result.json").read_text()) if (cdir / "result.json").exists() else {}
    r.update(status=rr.get("status", "no result"), seconds=rr.get("seconds"), error=rr.get("error", ""))
    pdfs = sorted((cdir / "artifacts").glob("n_f-pdf-*"))
    report = json.loads((cdir / "fill_report.json").read_text()) if (cdir / "fill_report.json").exists() and (cdir / "fill_report.json").stat().st_size else None
    r["report"] = report
    base = defaults.get(fixture, {})

    # Expected final value of every field: the case's expectation, else the untouched default.
    original = read_widgets(out_dir / "inputs" / fixture)
    expect = {}
    for w in original:
        if w["name"] in spec["expect"]:
            expect[w["name"]] = spec["expect"][w["name"]]
        elif w["name"] not in expect:
            expect[w["name"]] = base.get(w["name"], {"text": "", "checkbox": "off", "radio": None, "choice": ""}[w["kind"]])
    changed = {n for n in expect if n in spec["expect"] and spec["expect"][n] != next((w["value"] for w in original if w["name"] == n), None)}

    fields = []
    if pdfs:
        shutil_dest = cdir / "filled.pdf"
        shutil_dest.write_bytes(pdfs[0].read_bytes())
        widgets = read_widgets(shutil_dest)
        png_dir = cdir / "png"
        png_dir.mkdir(exist_ok=True)
        after = render(shutil_dest, png_dir)
        before = render(out_dir / "inputs" / fixture, None)
        seen_radio = set()
        for w in widgets:
            want = expect.get(w["name"])
            got = w["value"]
            if w["kind"] == "radio":
                if w["name"] in seen_radio:
                    continue  # one entry per radio group
                seen_radio.add(w["name"])
            ok = (got == want) or (want in (None, "") and got in (None, ""))
            must_change = w["name"] in changed
            untouched = base.get(w["name"], {"text": "", "checkbox": "off", "radio": None, "choice": ""}[w["kind"]])
            # "missed": still what the untouched form holds; "wrong": something else than expected.
            verdict = "ok" if ok else ("missed" if got in (untouched, None, "") else "wrong")
            visible = None
            if must_change and ok and w["kind"] in ("text", "choice", "checkbox"):
                img_b, _ = before[w["page"] - 1]
                img_a, size = after[w["page"] - 1]
                visible = changed_fraction(img_b, img_a, w["rect"], size[1]) > 0.004
            fields.append(dict(name=w["name"], kind=w["kind"], page=w["page"], expected=want, actual=got, verdict=verdict, mustChange=must_change, visible=visible))

    must = [f for f in fields if f["mustChange"]]
    hits = [f for f in must if f["verdict"] == "ok"]
    wrong = [f for f in fields if f["verdict"] == "wrong"]
    missed = [f for f in fields if f["verdict"] == "missed" and f["mustChange"]]
    invisible = [f for f in must if f["verdict"] == "ok" and f["visible"] is False]
    r.update(fields=fields, mustChange=len(must), hits=len(hits), wrong=[f["name"] for f in wrong], missed=[f["name"] for f in missed], invisible=[f["name"] for f in invisible])
    r["matchRate"] = round(len(hits) / len(must), 3) if must else 0.0

    # Report accuracy: every report entry must describe what really is in the PDF.
    if report:
        by_name = {}
        for f in fields:
            by_name.setdefault(f["name"], f)
        wrong_entries, methods = [], {}
        for e in report.get("filled", []):
            methods[e["method"]] = methods.get(e["method"], 0) + 1
            f = by_name.get(e["field"])
            actual = f["actual"] if f else None
            if f is None or str(e["value"]) != str(actual):
                wrong_entries.append(f"{e['key']}->{e['field']}: report {e['value']!r} / pdf {actual!r}")
        r["methods"] = methods
        r["reportMismatches"] = wrong_entries
        r["reportFilled"] = len(report.get("filled", []))
        r["unmatchedKeys"] = report.get("unmatchedKeys", [])
        r["warnings"] = report.get("warnings", [])
    else:
        r["methods"], r["reportMismatches"], r["reportFilled"], r["unmatchedKeys"], r["warnings"] = {}, [], 0, [], []

    checks = {
        "실행 성공": r["status"] == "succeeded",
        "일치율 ≥95%": r["matchRate"] >= 0.95,
        "오매핑(잘못된 값) 0": not r["wrong"],
        "채워진 값이 렌더에 보임": not r["invisible"] and bool(must),
        "리포트가 PDF 와 일치": report is not None and not r["reportMismatches"],
    }
    r["checks"] = checks
    r["pass"] = all(checks.values())
    all_ok &= r["pass"]
    results.append(r)

(out_dir / "results.json").write_text(json.dumps(dict(label=label, accepted=all_ok, cases=results), ensure_ascii=False, indent=1))

L = [f"# fill 품질 점검 — {label}", "", f"- 판정: **{'통과' if all_ok else '실패'}**", ""]
L += ["## 요약", "", "| 케이스 | 폼 | 실행 | 소요 | 일치 | 일치율 | 오매핑 | 누락 | 매핑 방식 | 리포트 오류 | 판정 |", "| :-- | :-- | :-: | --: | --: | --: | --: | --: | :-- | --: | :-: |"]
for r in results:
    L.append("| {} | {} | {} | {}s | {}/{} | {:.0%} | {} | {} | {} | {} | {} |".format(
        r["case"], r["fixture"], r["status"], r["seconds"], r["hits"], r["mustChange"], r["matchRate"],
        len(r["wrong"]), len(r["missed"]), ", ".join(f"{k} {v}" for k, v in sorted(r["methods"].items())) or "-",
        len(r["reportMismatches"]), "✓" if r["pass"] else "✗"))
L += ["", "## 케이스별 결과", ""]
for r in results:
    L += [f"### {r['case']} ({r['fixture']})", ""]
    if r["error"]:
        L.append(f"- 오류: {r['error']}")
    for name, ok in r["checks"].items():
        L.append(f"- {'✓' if ok else '✗'} {name}")
    L.append(f"- 매핑 방식: {r['methods'] or '-'} · 리포트 filled {r['reportFilled']}개 · 미매핑 키 {r['unmatchedKeys'] or '없음'}")
    if r["warnings"]:
        L.append(f"- 경고: {r['warnings']}")
    if r["reportMismatches"]:
