    exit 3
  fi
  if [[ "$NO_WEB" == true ]]; then
    engine_ip=$(docker inspect -f '{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}' "$(docker compose ps -q engine)" 2>/dev/null || true)
    if [[ -z "$engine_ip" ]]; then
