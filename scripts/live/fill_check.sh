#!/usr/bin/env bash
# Live quality check of the fill node (PDF form + JSON key/value pairs -> filled PDF) against the real OpenRouter LLM.
#
#   BASE_URL=<url> LIVE_CONFIRM=1 scripts/live/fill_check.sh [--out live-results] [--label NAME] [--cases ko,en,codes,multi]
#   LIVE_CONFIRM=1 scripts/live/fill_check.sh --with-verify-stack [...]   # isolated stack dochestra-verify:18080
#   LIVE_CONFIRM=1 scripts/live/fill_check.sh --with-verify-stack --no-web [...]
#       # starts only db + extractor + engine and talks to the engine's container IP: the check does not need the web
#       # image, so a broken / half-edited frontend does not block it
#
# Fixtures: engine/tests/fixtures/form_{ko,codes,multi}.pdf (generated by make_forms.py). Cases - each one is a
# bundle -> pick_pdf -> fill workflow with a json_input node, i.e. one fill run (one LLM mapping call):
#   ko     form_ko    keys a person would write in Korean (이름, 생년월일, 주소 -> address, 이메일 -> email, 동의함 -> 동의,
#                     성별 = "남자" for a radio that exports male/female, 지역 = "부산" for a combo with export busan, ...)
#   en     form_ko    English snake_case keys with typos (name, birthdate, adress, emial, agree: true, gender, region, memo)
#   codes  form_codes the same form with field names Text1..Text6, Check1, Group1, Dropdown1: the labels exist only as
#                     page text, so the keys cannot be matched by name at all
#   multi  form_multi 3 pages, the same field name repeated on several pages (name x2, phone x3), 5 radio groups of
#                     three widgets, checkboxes ("예" / "아니오"), labels above the fields
# Each case lists the expected final value of EVERY field (also the ones that must stay untouched).
#
# Checks: expected-value match rate over the fields that must change, wrong values (a field that holds something other
# than its expected value, i.e. a mis-mapping), fields that were left empty, mapping method distribution
# (exact / normalized / llm from _work/fill_report.json, read out of the isolated stack's engine container), report
# accuracy (every report entry equals the value really stored in the PDF), checkbox / radio / choice conversion, and
# whether every filled field is visibly drawn when the page is rendered with PDFium's form-fill (pixel change inside the
# widget rectangle; this is what shows whether Hangul values survive NeedAppearances). PNGs are written for a visual look.
# PDF fields are read with pypdf, pages rendered with pypdfium2 (one-off `uv run --with` environment, nothing is installed
# on the host).
#
# Results: <out>/<UTC timestamp>/fill-check/{report.md,results.json,<case>/{filled.pdf,fill_report.json,png/...}}.
# API keys are never read or printed (the engine inside the stack holds them). Without LIVE_CONFIRM=1 only the plan is
# printed. BASE_URL has no default on purpose (the user's own stack must not be hit by accident).
# Exit status: 0 when every case reaches >= 95 % with no wrong value, 1 otherwise, 3 for infrastructure problems.
set -euo pipefail

cd "$(dirname "$0")/../.."
ROOT=$(pwd)
FIXTURES="$ROOT/engine/tests/fixtures"

OUT_BASE="live-results"
LABEL="run"
CASES="ko,en,codes,multi"
WITH_STACK=false
NO_WEB=false

