  echo "[fill] isolated stack: project=$COMPOSE_PROJECT_NAME port=$WEB_PORT env=$ENV_FILE"
  stack_down() { docker compose down -v --remove-orphans >/dev/null 2>&1 || true; }
  docker compose down -v --remove-orphans >/dev/null 2>&1 || true
  services=()
  if [[ "$NO_WEB" == true ]]; then services=(engine); fi # compose starts its dependencies (db, extractor) too
  if ! docker compose up -d --build --wait "${services[@]}"; then
    echo "fill_check: the isolated stack failed to start" >&2
    docker compose logs --no-color --tail 40 engine >&2 || true
