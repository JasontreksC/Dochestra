fi

# ---- gate: plan only unless LIVE_CONFIRM=1 ---------------------------------------------------
if [[ "${LIVE_CONFIRM:-}" != 1 ]]; then
  echo "fill_check: PLAN ONLY (no workflows are created, no paid calls are made)"
  echo "  target : ${BASE_URL:-<isolated verify stack http://localhost:18080>}"
  echo "  cases  : ${SELECTED[*]}"
  echo "  per case: one fill run (one LLM mapping call for the keys that exact / normalized matching cannot resolve)"
  echo "  Set LIVE_CONFIRM=1 to run for real."
